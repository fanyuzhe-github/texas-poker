function buildCards(rawList, star, offset) {
  return rawList.map(([name, type, flavor], index) => {
    const no = offset + index + 1;
    return {
      id: `c${String(no).padStart(3, "0")}`,
      no,
      code: String(no).padStart(3, "0"),
      name,
      star,
      type,
      stage: STAGE_LABEL[star],
      flavor,
      dex: NATIONAL_DEX[name] || 0,
    };
  });
}

/** 完整卡池，按编号升序（也就是稀有度从低到高） */
export const CARD_POOL = [
  ...buildCards(STAR_1, 1, 0),
  ...buildCards(STAR_2, 2, STAR_1.length),
  ...buildCards(STAR_3, 3, STAR_1.length + STAR_2.length),
  ...buildCards(STAR_4, 4, STAR_1.length + STAR_2.length + STAR_3.length),
  ...buildCards(
    STAR_5,
    5,
    STAR_1.length + STAR_2.length + STAR_3.length + STAR_4.length
  ),
];

export const CARD_TOTAL = CARD_POOL.length;

/** 稀有度 → 该档位的所有卡 */
export const POOL_BY_STAR = CARD_POOL.reduce((map, card) => {
  const list = map[card.star] || [];
  list.push(card);
  map[card.star] = list;
  return map;
}, {});

const CARD_BY_ID = CARD_POOL.reduce((map, card) => {
  map[card.id] = card;
  return map;
}, {});

export function cardById(id) {
  return CARD_BY_ID[id] || null;
}

export function typeTone(type) {
  return TYPE_TONE[type] || TYPE_TONE.default;
}

/** 卡池里出现过的全部属性，图鉴页筛选用 */
export const ALL_TYPES = Array.from(
  CARD_POOL.reduce((set, card) => {
    set.add(card.type);
    return set;
  }, new Set())
);
